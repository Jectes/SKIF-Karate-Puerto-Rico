-- ---------- Core account and student records ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(btrim(full_name)) between 1 and 120),
  role public.app_role not null default 'parent',
  active boolean not null default false,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint active_profile_requires_approval check (not active or approved_at is not null)
);

-- Idempotent migration support for an earlier package version.
alter table public.profiles add column if not exists approved_at timestamptz;
update public.profiles
set approved_at = coalesce(approved_at, created_at)
where active and approved_at is null;
do $$ begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.profiles'::regclass
      and conname = 'active_profile_requires_approval'
  ) then
    alter table public.profiles
      add constraint active_profile_requires_approval check (not active or approved_at is not null);
  end if;
end $$;

