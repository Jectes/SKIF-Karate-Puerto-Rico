-- Server-verified attribution. Client-supplied actor IDs are overwritten.
DO $$
declare
  item text[];
begin
  foreach item slice 1 in array array[
    array['students', 'created_by', 'preserve'],
    array['guardian_students', 'created_by', 'preserve'],
    array['enrollments', 'created_by', 'preserve'],
    array['class_sessions', 'created_by', 'preserve'],
    array['student_badges', 'awarded_by', 'preserve'],
    array['student_goals', 'created_by', 'preserve'],
