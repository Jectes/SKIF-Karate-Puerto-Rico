-- ---------- Security helper functions ----------
create or replace function private.is_service_role()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, auth
as $$
  select session_user in ('postgres', 'supabase_admin')
    or coalesce(auth.jwt() ->> 'role', '') = 'service_role';
$$;

create or replace function private.current_role()
returns public.app_role
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $$
  select p.role
  from public.profiles p
  where p.id = auth.uid() and p.active = true;
$$;

create or replace function private.current_aal()
returns text
language sql
stable
security definer
set search_path = pg_catalog, auth
as $$
  select coalesce(auth.jwt() ->> 'aal', 'aal1');
$$;

create or replace function private.is_admin_aal2()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $$
  select private.is_service_role()
    or (private.current_role() = 'admin'::public.app_role and private.current_aal() = 'aal2');
$$;

create or replace function private.is_staff_aal2()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $$
  select private.is_service_role()
    or (
      private.current_role() in ('instructor'::public.app_role, 'admin'::public.app_role)
      and private.current_aal() = 'aal2'
    );
$$;

create or replace function private.is_direct_family(p_student_id uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.active = true
      and (
        (
          p.role = 'student'::public.app_role
          and exists (
            select 1 from public.students s
            where s.id = p_student_id and s.user_id = p.id
          )
        )
        or (
          p.role = 'parent'::public.app_role
          and exists (
            select 1 from public.guardian_students gs
            where gs.student_id = p_student_id
              and gs.guardian_user_id = p.id
              and gs.active = true
          )
        )
      )
  );
$$;

create or replace function private.can_access_student(p_student_id uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, private
as $$
  select private.is_staff_aal2() or private.is_direct_family(p_student_id);
$$;

