create or replace function private.set_updated_at()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  requested_name text;
begin
  requested_name := nullif(btrim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), '');
  insert into public.profiles (id, full_name, role, active)
  values (
    new.id,
    left(coalesce(requested_name, nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Dojo member'), 120),
    'parent'::public.app_role,
    false
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function private.protect_profile_security_fields()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
begin
  if old.created_at is distinct from new.created_at then
    raise exception 'Account creation timestamps are immutable.' using errcode = '42501';
  end if;

  if old.role is distinct from new.role
    or old.active is distinct from new.active
    or old.approved_at is distinct from new.approved_at then
    if not private.is_service_role() and not private.is_admin_aal2() then
      raise exception 'Only an MFA-verified administrator may change account roles, approval, or activation status.' using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;

create or replace function private.protect_student_identity_fields()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
begin
  if old.created_at is distinct from new.created_at then
    raise exception 'Student creation timestamps are immutable.' using errcode = '42501';
  end if;

  if old.user_id is distinct from new.user_id
    or old.display_name is distinct from new.display_name
    or old.age_group is distinct from new.age_group
    or old.is_minor is distinct from new.is_minor
    or old.status is distinct from new.status
    or old.joined_on is distinct from new.joined_on
    or old.created_by is distinct from new.created_by then
    if not private.is_service_role() and not private.is_admin_aal2() then
      raise exception 'Only an MFA-verified administrator may change student identity, account linkage, or lifecycle fields.' using errcode = '42501';
    end if;
  end if;

  return new;
end;
$$;

create or replace function private.protect_attribution_field()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  field_name text := tg_argv[0];
  update_mode text := coalesce(tg_argv[1], 'preserve');
  actor uuid;
  old_value text;
begin
  if private.is_service_role() then
    return new;
  end if;

  actor := auth.uid();
  if actor is null then
    raise exception 'An authenticated account is required.' using errcode = '42501';
  end if;

  if tg_op = 'INSERT' or update_mode = 'touch' then
    new := jsonb_populate_record(new, jsonb_build_object(field_name, actor));
    return new;
  end if;

  old_value := to_jsonb(old) ->> field_name;
  new := jsonb_populate_record(new, jsonb_build_object(field_name, old_value));
  return new;
end;
$$;

create or replace function private.audit_sensitive_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  row_data jsonb;
  record_key text;
begin
  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  record_key := case tg_table_name
    when 'guardian_students' then nullif(concat_ws(':', row_data ->> 'guardian_user_id', row_data ->> 'student_id'), '')
    when 'student_requirement_progress' then nullif(concat_ws(':', row_data ->> 'student_id', row_data ->> 'requirement_id'), '')
    when 'enrollments' then nullif(concat_ws(':', row_data ->> 'student_id', row_data ->> 'class_group_id'), '')
    else row_data ->> 'id'
  end;

  insert into public.audit_log (actor_user_id, action, table_name, record_id, details)
  values (
    auth.uid(),
    lower(tg_op),
    tg_table_name,
    nullif(record_key, ''),
    jsonb_strip_nulls(jsonb_build_object(
      'student_id', row_data ->> 'student_id',
      'session_id', row_data ->> 'session_id',
      'status', row_data ->> 'status',
      'role', row_data ->> 'role',
      'approved_at', row_data ->> 'approved_at',
      'consent_type', row_data ->> 'consent_type'
    ))
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

