    array['billing_items', 'created_by', 'preserve'],
    array['student_requirement_progress', 'assessed_by', 'touch'],
    array['attendance', 'recorded_by', 'touch']
  ] loop
    execute format('drop trigger if exists protect_%I_attribution on public.%I', item[1], item[1]);
    execute format(
      'create trigger protect_%I_attribution before insert or update on public.%I for each row execute function private.protect_attribution_field(%L, %L)',
