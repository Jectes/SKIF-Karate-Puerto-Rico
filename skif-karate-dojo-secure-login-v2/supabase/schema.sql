-- S.K.I.F. Puerto Rico Honbu Dojo secure portal database
-- Target: Supabase PostgreSQL
-- Run this file in the Supabase SQL editor on a new project.
--
-- Privacy choices built into this schema:
--   * No plaintext passwords (Supabase Auth owns authentication).
--   * No email duplication in application tables.
--   * No exact date of birth, SSN, government ID, card number, or bank data.
--   * Parents and students can only read records linked to their account.
--   * Instructor/admin access to student records requires an AAL2 (MFA) JWT.
--   * Sensitive writes create metadata-only audit entries.

begin;

create extension if not exists pgcrypto;
create schema if not exists private;
revoke all on schema private from public;

